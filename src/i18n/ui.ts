export type UiKey = keyof (typeof ui)['nl'];

export const t = (lang: Lang, key: UiKey): string => ui[lang][key];

export const formatPrice = (lang: Lang, cents: number | null): string =>
  cents === null
    ? t(lang, 'price.placeholder')
    : new Intl.NumberFormat(lang === 'nl' ? 'nl-NL' : 'en-IE', { style: 'currency', currency: 'EUR' }).format(cents / 100);
